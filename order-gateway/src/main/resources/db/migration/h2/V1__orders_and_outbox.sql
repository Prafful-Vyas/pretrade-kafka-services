-- H2 (MSSQLServer mode) equivalent of db/migration/sqlserver/V1, used by tests.
-- Differences: TIMESTAMP WITH TIME ZONE for DATETIMEOFFSET, no INCLUDE/filtered indexes.

CREATE TABLE orders (
    id               VARCHAR(36)       NOT NULL PRIMARY KEY,
    idempotency_key  VARCHAR(64)       NOT NULL,
    request_hash     VARCHAR(64)        NOT NULL,
    account_id       VARCHAR(32)       NOT NULL,
    instrument       VARCHAR(12)        NOT NULL,
    side             VARCHAR(4)        NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity         BIGINT            NOT NULL CHECK (quantity > 0),
    limit_price      DECIMAL(18, 6)    NOT NULL,
    currency         VARCHAR(3)         NOT NULL,
    status           VARCHAR(16)       NOT NULL,
    reject_reasons   VARCHAR(400)      NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version          BIGINT            NOT NULL
);
CREATE UNIQUE INDEX ux_orders_idempotency_key ON orders (idempotency_key);
CREATE INDEX ix_orders_account_created ON orders (account_id, created_at);

CREATE TABLE outbox_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic         VARCHAR(128)      NOT NULL,
    message_key   VARCHAR(64)       NOT NULL,
    payload       VARCHAR(4000)     NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published_at  TIMESTAMP(6) WITH TIME ZONE NULL
);
CREATE INDEX ix_outbox_published ON outbox_event (published_at, id);
